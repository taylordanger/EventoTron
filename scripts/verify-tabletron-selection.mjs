import assert from "node:assert/strict";
const { chromium } = await import(process.env.EVENTOTRON_PLAYWRIGHT_MODULE || "playwright");
const target = new URL(process.env.EVENTOTRON_QA_URL || "http://invalid");
if (process.env.EVENTOTRON_ISOLATED_QA !== "1" || target.protocol !== "http:" || !["localhost", "127.0.0.1"].includes(target.hostname) || ["", "3000", "3001", "3101"].includes(target.port) || target.pathname !== "/" || target.search || target.hash || target.username || target.password) throw new Error("Use an isolated local QA server, never the daily-use database.");
const base = target.origin;
async function api(path, method = "GET", body) {
  const response = await fetch(base + path, { method, headers: { "content-type": "application/json" }, body: body ? JSON.stringify(body) : undefined });
  const data = await response.json(); assert.ok(response.ok, JSON.stringify(data)); return data;
}
const suffix = Date.now();
const pat = { id: `pat-qa-${suffix}`, title: "Pat Dunne QA", date: "2026-09-01", kind: "rental", space: "Auditorium", attendees: 20, eventTime: "10:00 AM - 12:00 PM", rentalTime: "", manager: "", contact: "", phone: "", email: "", description: "", planningNotes: "", mod: "", vacation: "", rentalTotal: 0, cateringTotal: 0, discountRate: 0, deposit: 0, paymentNotes: "", quoteEnteredBy: "", requestedItems: "" };
await api("/api/events", "PATCH", { event: pat, expectedUpdatedAt: null });
const browser = await chromium.launch({ headless: true, ...(process.env.EVENTOTRON_CHROME_PATH ? { executablePath: process.env.EVENTOTRON_CHROME_PATH } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(10000);
  await page.route("**/api/events", async route => {
    if (route.request().method() !== "GET") return route.continue();
    const data = await api("/api/events");
    await route.fulfill({ json: { ...data, events: data.events.filter(event => event.id.endsWith(String(suffix))) } });
  });
  const errors = []; page.on("pageerror", error => { errors.push(error.message); console.log("PAGE ERROR", error.message); });
  await page.goto(`${base}/tabletron?event=${pat.id}`);
  await page.waitForFunction(() => document.querySelector(".project-name input")?.value === "Pat Dunne QA");
  await page.waitForFunction(id => localStorage.getItem(`tabletron-project-v2:event:${id}`), pat.id);
  assert.ok(page.url().includes(`event=${pat.id}`));
  const legacy = await page.evaluate(id => localStorage.getItem(`tabletron-project-v2:event:${id}`), pat.id);
  await page.evaluate(({ legacy, pat }) => {
    localStorage.setItem("tabletron-project-v2", legacy);
    localStorage.setItem("eventotron-events-v1", JSON.stringify({ events: [pat], selectedId: pat.id, openIds: [pat.id] }));
  }, { legacy, pat });
  await page.goto(`${base}/`);
  await page.waitForTimeout(1200);
  const tab = page.locator('.folder-tabs a').filter({ hasText: "Tabletron" });
  assert.equal(await tab.getAttribute("href"), "/tabletron", "no event today must not silently select last event");
  await tab.click();
  await page.waitForFunction(() => document.querySelector(".project-name input")?.value === "Lincoln City Cultural Center Event Plan");
  await page.waitForTimeout(700);
  assert.equal(await page.locator(".event-list button").count(), 0);
  assert.equal(await page.evaluate(() => localStorage.getItem("tabletron-project-v2")), legacy, "old cache must not be deleted");
  await page.locator(".project-name input").fill("Standalone room study");
  await page.waitForTimeout(650);
  await page.reload();
  await page.waitForFunction(() => document.querySelector(".project-name input")?.value === "Standalone room study");
  const today = await page.evaluate(() => { const d = new Date(); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2,"0")}-${String(d.getDate()).padStart(2,"0")}`; });
  const fresh = { ...pat, id: `today-qa-${suffix}`, title: "Today's QA event", date: today };
  await api("/api/events", "PATCH", { event: fresh, expectedUpdatedAt: null });
  await page.goto(`${base}/`);
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('.folder-tabs a[href^="/tabletron"]').getAttribute("href"), "/tabletron", "today's events must not automatically become active files");
  await page.getByRole("button", { name: "Open Today's QA event", exact: true }).click();
  await page.waitForFunction(id => document.querySelector('.folder-tabs a[href^="/tabletron"]')?.getAttribute("href") === `/tabletron?event=${id}`, fresh.id);
  await page.locator('.folder-tabs a').filter({ hasText: "Tabletron" }).click();
  await page.waitForFunction(() => document.querySelector(".project-name input")?.value === "Today's QA event");
  await page.waitForFunction(() => document.querySelector(".tabletron-applet .save-state")?.textContent === "SAVED");
  await page.reload();
  await page.waitForFunction(() => document.querySelector(".project-name input")?.value === "Today's QA event");
  assert.ok(page.url().includes(`event=${fresh.id}`));
  if (await page.locator(".event-backdrop").count()) await page.locator(".event-backdrop").getByRole("button", { name: "×", exact: true }).click();
  await page.screenshot({ path: "/private/tmp/eventotron-current-event-fix.png", fullPage: true });
  await page.goto(`${base}/tabletron`);
  await page.waitForFunction(() => document.querySelector(".project-name input")?.value === "Standalone room study");
  const transfer = await api("/api/tabletron-transfers", "POST", { meal: { id: `meal-qa-${suffix}`, name: "QA lunch", tabletronEventId: fresh.id, date: today, guests: 20 }, packet: { mealName: "QA lunch", date: today, guests: 20, recipes: [], stores: [], unpriced: [], total: 0 } });
  await page.goto(base + transfer.tabletronUrl);
  await page.waitForFunction(() => document.querySelector(".project-name input")?.value === "Today's QA event");
  await page.waitForTimeout(1200);
  const saved = await api(`/api/event-app-state?eventId=${fresh.id}&app=tabletron`);
  assert.equal(saved.payload.events.find(event => event.id === fresh.id).food.mealName, "QA lunch", "meal transfer must use the canonical target event, not standalone cache");
  await page.goto(`${base}/scheduluotron?event=${pat.id}`);
  await page.waitForFunction(() => document.querySelector(".sched-title input")?.value === "Pat Dunne QA");
  await page.locator(".sched-title input").fill("Custom Pat timetable");
  await page.waitForTimeout(1300);
  const schedule = await api(`/api/event-app-state?eventId=${pat.id}&app=scheduluotron`);
  assert.equal(schedule.payload.eventName, "Custom Pat timetable");
  await page.evaluate(plan => localStorage.setItem("eventotron-scheduluotron-v1", JSON.stringify(plan)), schedule.payload);
  await page.goto(`${base}/scheduluotron`);
  await page.waitForFunction(() => document.querySelector(".sched-title input")?.value === "New Event Timeline");
  await page.waitForTimeout(600);
  assert.equal(await page.locator('.scheduluotron-app input[type="date"]').inputValue(), today);
  await page.locator(".sched-title input").fill("Standalone schedule study");
  await page.waitForTimeout(750);
  await page.reload();
  await page.waitForFunction(() => document.querySelector(".sched-title input")?.value === "Standalone schedule study");
  await page.goto(`${base}/scheduluotron?event=${fresh.id}`);
  await page.waitForFunction(() => document.querySelector(".sched-title input")?.value === "Today's QA event");
  await page.reload();
  await page.waitForFunction(() => document.querySelector(".sched-title input")?.value === "Today's QA event");
  await page.goto(`${base}/scheduluotron?event=${pat.id}`);
  await page.waitForFunction(() => document.querySelector(".sched-title input")?.value === "Custom Pat timetable");
  await page.goto(`${base}/scheduluotron`);
  await page.waitForFunction(() => document.querySelector(".sched-title input")?.value === "Standalone schedule study");
  await page.screenshot({ path: "/private/tmp/eventotron-schedule-selection-fix.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("PASS: Tabletron and Scheduluotron ignore unrelated legacy event caches, preserve standalone work and saved event plans, survive refresh, and transfer meals to the correct event; no browser errors.");
} finally { await browser.close(); }
